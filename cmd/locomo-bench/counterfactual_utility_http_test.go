func TestUtilityMapFinalSignalBasic(t *testing.T) {
	// content == reconstructed bytes (no reasoning prefix); final answer is the
	// trailing suffix "Oslo". Each final token has two finite alternatives.
	tokens := []utilityLogprobToken{
		{Token: "Os", Bytes: []byte("Os"), Logprob: -0.1, Top1: -0.1, Top2: -2.0},
		{Token: "lo", Bytes: []byte("lo"), Logprob: -0.2, Top1: -0.2, Top2: -2.1},
	}
	sig, err := utilityMapFinalSignal("Oslo", tokens)
	if err != nil {
		t.Fatalf("map: %v", err)
	}
	if sig.Status != "available" {
		t.Fatalf("status = %s reason=%s, want available", sig.Status, sig.Reason)
	}
	if sig.FinalTokenCount != 2 || sig.FinalByteStart != 0 || sig.FinalByteEnd != 4 {
		t.Fatalf("span = [%d,%d) n=%d, want [0,4) n=2", sig.FinalByteStart, sig.FinalByteEnd, sig.FinalTokenCount)
	}
	if len(sig.Features) != 3 {
		t.Fatalf("features len = %d, want 3", len(sig.Features))
	}
	// final_mean_logprob = (-0.1 + -0.2)/2 = -0.15
	// p10 (n=2, index ceil(0.2)-1 = 0) = -0.2 (nearest-rank 10th percentile)
	// margin mean = (1.9 + 1.9)/2 = 1.9
	if sig.Features[0] < -0.16 || sig.Features[0] > -0.14 {
		t.Fatalf("mean logprob = %v, want ~-0.15", sig.Features[0])
	}
	if sig.Features[1] < -0.21 || sig.Features[1] > -0.19 {
		t.Fatalf("p10 logprob = %v, want ~-0.20", sig.Features[1])
	}
	if sig.Features[2] < 1.89 || sig.Features[2] > 1.91 {
		t.Fatalf("margin = %v, want ~1.90", sig.Features[2])
	}
}

