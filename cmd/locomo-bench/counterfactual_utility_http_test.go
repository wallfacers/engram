func TestUtilityLogprobCallerRequestShape(t *testing.T) {
	var gotBody map[string]any
	var gotHeaders http.Header
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		raw, _ := io.ReadAll(r.Body)
		_ = json.Unmarshal(raw, &gotBody)
		gotHeaders = r.Header
		w.Write([]byte(`{"choices":[{"message":{"content":"Oslo"},"logprobs":{"content":[
			{"token":"Os","bytes":[79,115],"logprob":-0.1,"top_logprobs":[{"token":"Os","bytes":[79,115],"logprob":-0.1},{"token":"No","bytes":[78,111],"logprob":-2.0}]},
			{"token":"lo","bytes":[108,111],"logprob":-0.2,"top_logprobs":[{"token":"lo","bytes":[108,111],"logprob":-0.2},{"token":"mo","bytes":[109,111],"logprob":-2.1}]}
		]}}],"usage":{"prompt_tokens":10,"completion_tokens":2}}`))
	}))
	defer srv.Close()

	caller, err := utilityNewLogprobCaller(utilityLogprobCallerConfig{
		BaseURL: srv.URL, Model: "test-model", MaxTokens: 8000, MaxModelLen: utilityMaxModelLen,
	})
	if err != nil {
		t.Fatalf("new caller: %v", err)
	}
	completion, err := caller.complete(context.Background(), "sys", "user")
	if err != nil {
		t.Fatalf("complete: %v", err)
	}
	// temperature must be omitted from the wire shape.
	if _, has := gotBody["temperature"]; has {
		t.Fatalf("temperature field must be omitted, got %v", gotBody["temperature"])
	}
	if gotBody["logprobs"] != true {
		t.Fatalf("logprobs = %v, want true", gotBody["logprobs"])
	}
	if gotBody["top_logprobs"] != float64(2) {
		t.Fatalf("top_logprobs = %v, want 2", gotBody["top_logprobs"])
	}
	if gotBody["stream"] != false {
		t.Fatalf("stream = %v, want false", gotBody["stream"])
	}
	if completion.Content != "Oslo" || len(completion.Tokens) != 2 {
		t.Fatalf("completion = %+v, want content Oslo with 2 tokens", completion)
	}
	if completion.Usage.InputTokens != 10 || completion.Usage.OutputTokens != 2 {
		t.Fatalf("usage = %+v, want 10/2", completion.Usage)
	}
	if gotHeaders.Get("Authorization") != "" {
		t.Fatalf("empty key must not set Authorization header")
	}
}

