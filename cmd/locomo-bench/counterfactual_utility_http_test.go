func TestUtilityRawResponsePrivacy(t *testing.T) {
	// Failure errors must not embed the raw provider body or endpoint.
	secret := "secret-upstream-body-xyz"
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.WriteHeader(http.StatusBadRequest)
		w.Write([]byte(`{"error":"` + secret + `"}`))
	}))
	defer srv.Close()
	caller, err := utilityNewLogprobCaller(utilityLogprobCallerConfig{BaseURL: srv.URL, Model: "m"})
	if err != nil {
		t.Fatal(err)
	}
	_, err = caller.complete(context.Background(), "s", "u")
	if err == nil {
		t.Fatal("expected error")
	}
	if strings.Contains(err.Error(), secret) {
		t.Fatalf("failure error leaked raw provider body: %v", err)
	}
	if strings.Contains(err.Error(), srv.URL) {
		t.Fatalf("failure error leaked endpoint: %v", err)
	}
}

