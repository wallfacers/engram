func TestUtilityMapFinalSignalUnavailableReasons(t *testing.T) {
	cases := []struct {
		name    string
		content string
		tokens  []utilityLogprobToken
		want    string
	}{
		{
			name:    "content not suffix of generated bytes",
			content: "Oslo", // generated bytes reconstruct to "Oslovakia"
			tokens: []utilityLogprobToken{
				{Token: "Oslo", Bytes: []byte("Oslo"), Logprob: -0.1, Top1: -0.1, Top2: -2.0},
				{Token: "vakia", Bytes: []byte("vakia"), Logprob: -0.2, Top1: -0.2, Top2: -2.1},
			},
			want: "content_not_generated_suffix",
		},
		{
			name:    "final answer empty",
			content: "<think>no answer</think>", // nothing after the closing tag
			tokens: []utilityLogprobToken{
				{Token: "<think>no answer</think>", Bytes: []byte("<think>no answer</think>"), Logprob: -0.1, Top1: -0.1, Top2: -2.0},
			},
			want: "empty_final",
		},
		{
			name:    "missing top2 alternative",
			content: "Oslo",
			tokens: []utilityLogprobToken{
				{Token: "Os", Bytes: []byte("Os"), Logprob: -0.1, Top1: -0.1, Top2: 0}, // Top2 zero means absent
				{Token: "lo", Bytes: []byte("lo"), Logprob: -0.2, Top1: -0.2, Top2: -2.1},
			},
			want: "missing_top2",
		},
		{
			name:    "non-finite logprob",
			content: "Oslo",
			tokens: []utilityLogprobToken{
				{Token: "Os", Bytes: []byte("Os"), Logprob: -0.1, Top1: -0.1, Top2: -2.0},
				{Token: "lo", Bytes: []byte("lo"), Logprob: nan(), Top1: -0.2, Top2: -2.1},
			},
			want: "non_finite_probability",
		},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			sig, err := utilityMapFinalSignal(c.content, c.tokens)
			if err != nil {
				t.Fatalf("map: %v", err)
			}
			if sig.Status != "unavailable" {
				t.Fatalf("status = %s, want unavailable", sig.Status)
			}
			if sig.Reason != c.want {
				t.Fatalf("reason = %s, want %s", sig.Reason, c.want)
			}
		})
	}
}

func TestUtilityMapFinalSignalUTF8AndBoundary(t *testing.T) {
	// UTF-8 multibyte content: byte offsets must be token boundaries. The final
	// answer "答案：北京" is the trailing suffix after the thinking delimiter.
	content := "<think>思考</think>\n答案：北京"
	tokens := []utilityLogprobToken{
		{Token: "<think>", Bytes: []byte("<think>"), Logprob: -0.3, Top1: -0.3, Top2: -1.5},
		{Token: "思考", Bytes: []byte("思考"), Logprob: -0.5, Top1: -0.5, Top2: -2.0},
		{Token: "</think>\n", Bytes: []byte("</think>\n"), Logprob: -0.8, Top1: -0.8, Top2: -2.5},
		{Token: "答案：", Bytes: []byte("答案："), Logprob: -0.3, Top1: -0.3, Top2: -1.5},
		{Token: "北京", Bytes: []byte("北京"), Logprob: -0.1, Top1: -0.1, Top2: -1.2},
	}
	sig, err := utilityMapFinalSignal(content, tokens)
	if err != nil {
		t.Fatalf("map: %v", err)
	}
	if sig.Status != "available" {
		t.Fatalf("status = %s reason=%s, want available", sig.Status, sig.Reason)
	}
	// final "答案：北京" spans bytes [22,37): "<think>"=7 + "思考"=6 + "</think>\n"=9.
	if sig.FinalByteStart != 22 || sig.FinalByteEnd != 37 {
		t.Fatalf("span = [%d,%d), want [22,37)", sig.FinalByteStart, sig.FinalByteEnd)
	}
	if sig.FinalLengthStratum != "2-4" {
		t.Fatalf("stratum = %s, want 2-4", sig.FinalLengthStratum)
	}
}

